import type { Role } from '@yenisey/types';

/**
 * Клуб, в котором выполняется запрос, и роль человека именно в нём.
 *
 * Заменяет собой tenantId и role, которые раньше приезжали в access-токене.
 * Теперь клуб приходит участком адреса (/api/clubs/:slug/...), а роль
 * читается из TenantMembership на каждый запрос: аккаунт один на платформу,
 * и «роль пользователя» без указания клуба смысла не имеет.
 */
export interface ClubContext {
  /** User.id — тот же, что в `sub` токена. Продублирован ради удобства сервисов. */
  userId: string;
  tenantId: string;
  slug: string;
  /**
   * Роли в этом клубе — несколько сразу (решение владельца от 26.09.2026).
   *
   * У человека без привязки к клубу здесь `['CLIENT']`: по ТЗ записаться в
   * клуб может любой пользователь платформы, вступать в него не требуется.
   * Такой посетитель проходит клиентские маршруты, а привязка заводится
   * первым действием, за которым стоят деньги или место в расписании.
   */
  roles: Role[];
  /**
   * Есть ли строка TenantMembership на самом деле.
   *
   * Различать важно там, где сервис собирается писать: анкету клиента нельзя
   * завести раньше привязки — внешний ключ целится в неё.
   */
  joined: boolean;
}
