/**
 * Поиск города по строке: разбор ввода в шаблоны LIKE.
 *
 * Чистый модуль без относительных импортов — его гоняет `node --test`.
 *
 * Совпадением считается начало названия или начало любого слова в нём:
 * «новг» находит и Великий, и Нижний Новгород, «петер» — Санкт-Петербург.
 * Середина слова совпадением не считается: «ярск» нашёл бы полсотни городов,
 * и ни одного из тех, что человек имел в виду.
 *
 * «Е» и «ё» равнозначны: «Орел» должен найти Орёл, а «Королев» — Королёв.
 * Буква заменяется подстановкой одного символа — лишнего она почти не
 * находит, а столбец с нормализованным названием ради этого не нужен.
 */
export interface CityPatterns {
  /** Начало названия — такие совпадения идут первыми. */
  prefix: string;
  /** Начало слова после пробела или дефиса. */
  word: string;
  hyphen: string;
}

/** Пусто после обрезки — `null`: ищут тогда самые крупные города. */
export function cityPatterns(input: string | undefined): CityPatterns | null {
  const query = (input ?? '').trim().toLowerCase().replace(/\s+/g, ' ');

  if (query === '') return null;

  // Сначала экранирование: пользовательские % и _ не должны становиться
  // подстановками. Обратная косая — экранирующий символ LIKE по умолчанию.
  const escaped = query.replace(/[\\%_]/g, (char) => `\\${char}`).replace(/[её]/g, '_');

  return { prefix: `${escaped}%`, word: `% ${escaped}%`, hyphen: `%-${escaped}%` };
}

/** Сколько подсказок отдать: по умолчанию 20, не больше 50. */
export function cityLimit(value: number | undefined): number {
  if (value === undefined || !Number.isInteger(value)) return 20;

  return Math.min(Math.max(value, 1), 50);
}
