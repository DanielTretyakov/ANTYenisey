/**
 * Петлевые адреса. Нужны, чтобы не применять грубое ограничение частоты к
 * запросам с самой машины разработчика: `pnpm smoke` шлёт десятки запросов
 * подряд с одного адреса и упирался бы в лимит вместо того, чтобы проверять
 * авторизацию.
 *
 * В production исключение не действует: там перед приложением стоит nginx, и
 * запрос с петлевого адреса означал бы неверно настроенный `trust proxy`, а не
 * локальную разработку.
 */
const LOOPBACK = new Set(['127.0.0.1', '::1', '::ffff:127.0.0.1']);

export function isLoopback(address: string | undefined): boolean {
  return address !== undefined && LOOPBACK.has(address);
}
