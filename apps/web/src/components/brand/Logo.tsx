import { cn } from '@/lib/cn';

/** Пропорции файла `public/brand/logo.png` — из него считается ширина. */
const LOGO_WIDTH = 2158;
const LOGO_HEIGHT = 399;

/**
 * Логотип академии — оригинальный файл из брендбука.
 *
 * Название набирать рядом не нужно и нельзя: оно часть логотипа, со своей
 * гарнитурой, которая ни одним интерфейсным шрифтом не заменяется.
 *
 * Логотип нарисован тёмной краской по прозрачному фону, поэтому на тёмном фоне
 * его нужно обращать. Обращение живёт в CSS (`.brand-logo` в globals.css) и
 * работает двумя способами: само по теме и принудительно, через `onDark` — на
 * изумрудной подложке логотип обязан быть светлым в любой теме.
 *
 * Обращение фильтром, а не вторым файлом: копия пришлось бы обновлять вручную
 * при каждой замене логотипа, и рано или поздно две версии разъехались бы.
 */
export function Logo({
  className,
  /** Высота логотипа в rem. Ширина считается от неё по пропорциям файла. */
  height = 1.75,
  /** Логотип стоит на тёмной подложке независимо от темы страницы. */
  onDark = false,
}: {
  className?: string;
  height?: number;
  onDark?: boolean;
}) {
  return (
    <img
      src="/brand/logo.png"
      alt="Академия настольного тенниса «Енисей»"
      width={LOGO_WIDTH}
      height={LOGO_HEIGHT}
      // Размеры атрибутами — чтобы браузер зарезервировал место до загрузки и
      // шапка не дёргалась.
      className={cn('brand-logo', onDark && 'brand-logo--on-dark', className)}
      style={{ height: `${height}rem`, width: `${(height * LOGO_WIDTH) / LOGO_HEIGHT}rem` }}
    />
  );
}
