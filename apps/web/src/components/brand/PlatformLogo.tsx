import { cn } from '@/lib/cn';

/**
 * Знак платформы: стол, сетка и мяч в полёте.
 *
 * Нарисован `currentColor`, кроме мяча. Мяч — единственная цветная деталь, и
 * цвет у него не семантический, а предметный (`--ball`): оранжевый шарик не
 * спорит ни с изумрудом платформы, ни с фирменным цветом клуба, который на
 * клубных страницах подменяет `--accent`. Знак поэтому не приходится ни
 * инвертировать фильтром, ни держать вторым файлом для тёмной темы — он берёт
 * цвет текста от того места, куда его поставили.
 *
 * Пропорции квадратные и линии толстые намеренно: этот же знак идёт в favicon,
 * а там он живёт на 16 пикселях.
 */
export function PlatformMark({ className }: { className?: string }) {
  return (
    <svg
      viewBox="0 0 32 32"
      aria-hidden="true"
      focusable="false"
      className={cn('h-[1em] w-[1em] shrink-0', className)}
    >
      {/* Стол — линия, из которой вырастает подчёркивание словесной части. */}
      <rect x="3" y="22" width="26" height="3.5" rx="1.75" fill="currentColor" />
      {/* Сетка. Приглушена, чтобы на мелком кегле не слипалась со столом. */}
      <rect x="15" y="16.5" width="2" height="5.5" rx="1" fill="currentColor" opacity="0.45" />
      {/* Мяч — над столом и правее: подача, а не натюрморт. */}
      <circle cx="23" cy="10" r="4.5" fill="var(--ball)" />
    </svg>
  );
}

/**
 * Логотип платформы: знак и слово «КНТ».
 *
 * «КНТ» — клубы настольного тенниса. Платформа продаётся клубам, и её смысл в
 * том, что она собирает их в одном месте; отраслевую аббревиатуру этой
 * аудитории не нужно объяснять.
 *
 * Столкновения с названиями клубов не будет, хотя клуб «КНТ „Саяны“» на
 * платформе уже есть: клубный знак — монограмма СОБСТВЕННОГО имени («СА»),
 * аббревиатуру организационной формы `monogram()` пропускает намеренно (см.
 * `components/club/ClubMark.tsx`). Знак платформы монограммой не бывает
 * никогда — только этим логотипом.
 *
 * Слово набирается Unbounded, а не лежит в кривых: у знака академии «Енисей»
 * своя гарнитура из брендбука, которую нечем заменить, а у платформы гарнитура
 * та же, что в заголовках интерфейса.
 */
export function PlatformLogo({
  className,
  /** Высота логотипа в rem. Кегль слова и размер знака считаются от неё. */
  height = 1.75,
  /** Логотип стоит на тёмной подложке независимо от темы страницы. */
  onDark = false,
}: {
  className?: string;
  height?: number;
  onDark?: boolean;
}) {
  return (
    <span
      className={cn(
        'inline-flex items-center font-display leading-none',
        onDark ? 'text-ink-0' : 'text-text',
        className,
      )}
      // Кегль привязан к высоте логотипа: знак нарисован в em, слово — тоже,
      // поэтому пара масштабируется одним числом и нигде не разъезжается.
      style={{ fontSize: `${height * 0.62}rem`, gap: `${height * 0.19}rem` }}
    >
      <PlatformMark className="text-[1.35em]" />
      <span style={{ letterSpacing: '0.02em' }}>КНТ</span>
    </span>
  );
}
