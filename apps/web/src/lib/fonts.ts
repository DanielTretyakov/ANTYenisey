import { Onest, Unbounded } from 'next/font/google';

/**
 * Шрифтовая пара.
 *
 * Onest — весь интерфейс. Современный гротеск, нарисованный сразу с полной
 * кириллицей (а не дорисованной к латинице позже), с ровным ритмом и
 * различимыми в мелком кегле цифрами — по ним читают время занятия и цену.
 *
 * Unbounded — заголовки первого уровня и крупные акценты. Широкий
 * геометрический гротеск: те же плоские окончания и одинаковая толщина штриха,
 * что в логотипе академии, поэтому заголовок и знак читаются как одно
 * семейство. Мелким кеглем не набирается — на нём широкие пропорции только
 * мешают.
 *
 * Оба берутся с кириллицей явно: без `subsets` Next подгрузит одну латиницу,
 * и русский текст молча уедет на запасное семейство.
 *
 * Отказ от Playfair Display: антиква из презентации бренда рассчитана на
 * проектор, а расписание и формы читают с телефона.
 */
export const onest = Onest({
  subsets: ['cyrillic', 'latin'],
  variable: '--font-onest',
  display: 'swap',
  weight: ['400', '500', '600', '700'],
  fallback: ['system-ui', 'Segoe UI', 'Roboto', 'sans-serif'],
});

export const unbounded = Unbounded({
  subsets: ['cyrillic', 'latin'],
  variable: '--font-unbounded',
  display: 'swap',
  weight: ['300', '400', '500'],
  fallback: ['system-ui', 'Segoe UI', 'sans-serif'],
});
