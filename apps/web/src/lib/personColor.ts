/**
 * Цвета сетки расписания: заливка клетки и метка.
 *
 * Здесь же живут обе формулы смешивания, потому что применяет их не только
 * раздача цветов людям, но и палитра назначений (`SchedulePalette.tsx`), а
 * относительных импортов в этом модуле быть не может: его тесты идут через
 * `node --test`, который требует расширение `.ts`, а сборка его не принимает
 * (см. CLAUDE.md). Вынести формулы в соседний файл значило бы либо нарушить
 * это правило, либо развести две копии одной арифметики.
 *
 * Почему не классы Tailwind, как было раньше. Клетки были написаны сырыми
 * `bg-sky-500/55`, и это единственное место, где ломалась тёмная тема:
 * насыщенный полупрозрачный цвет по чёрному фону даёт грязь, а подпись поверх
 * него не читается. Теперь цвет вычисляется из краски и поверхности через
 * `color-mix` — тот же приём, которым `clubTheme.ts` подмешивает фирменный
 * цвет клуба, — и обе темы обслуживаются одним набором красок.
 */

/**
 * Заливка клетки: краска, разбавленная поверхностью карточки.
 *
 * Доля краски задана токеном `--tint-fill` и зависит от темы: по светлой
 * заливка бледная (на ней читается тёмная подпись), по тёмной — плотнее,
 * иначе краска тонет в фоне.
 *
 * Смешивается именно с `--surface-raised`, а не с `--surface`: сетка стоит на
 * карточке, и разбавлять цветом другой поверхности значило бы промахнуться
 * мимо того фона, на котором клетка окажется.
 */
export const tintFill = (paint: string): string =>
  `color-mix(in oklab, ${paint} var(--tint-fill), var(--surface-raised))`;

/**
 * Насыщенная метка: кружок в легенде, полоска назначения, чип палитры.
 *
 * По светлой теме это сама краска, по тёмной она высветляется (`--tint-mark`):
 * тёмно-синий по почти чёрному фону не виден вовсе.
 */
export const tintMark = (paint: string): string =>
  `color-mix(in oklab, ${paint} var(--tint-mark), var(--ink-0))`;

/**
 * Краски, закреплённые за людьми.
 *
 * Порядок менять нельзя: цвет человека вычисляется его местом в этом списке, и
 * перестановка перекрасила бы все уже составленные расписания. Изумруд первым —
 * он же фирменный цвет платформы, и чаще всего в сетке стоит именно тренер.
 */
const PALETTE = [
  'var(--brand-600)',
  'var(--hue-blue)',
  'var(--hue-amber)',
  'var(--hue-violet)',
  'var(--hue-rose)',
  'var(--hue-teal)',
  'var(--hue-indigo)',
  'var(--hue-orange)',
  'var(--hue-cyan)',
  'var(--hue-plum)',
] as const;

export interface PersonColor {
  /** Цвет заливки клетки. Ставится в `style`, а не классом: краска вычисляемая. */
  cell: string;
  /** Цвет кружка в легенде и в палитре. */
  dot: string;
}

/**
 * Раздача цветов по списку людей.
 *
 * Список сортируется, чтобы цвет человека не прыгал от того, в каком порядке
 * пришёл ответ сервера: перекрасившееся за ночь расписание сбивает с толку
 * сильнее, чем отсутствие цвета вовсе.
 *
 * Цвета раздаются по порядку в отсортированном списке, а не хешем от
 * идентификатора: хеш даёт коллизии, и двум тренерам смежных окон вполне может
 * достаться один цвет — ровно то, что эта затея должна была исключить.
 *
 * Когда людей больше, чем цветов, палитра идёт по кругу — соседние по списку
 * всё равно различаются, а одинаковый цвет достаётся людям, отстоящим друг от
 * друга на всю палитру.
 */
export function personColors(ids: readonly string[]): Map<string, PersonColor> {
  const colors = new Map<string, PersonColor>();
  const sorted = [...new Set(ids)].sort();

  sorted.forEach((id, index) => {
    const paint = PALETTE[index % PALETTE.length]!;

    colors.set(id, { cell: tintFill(paint), dot: tintMark(paint) });
  });

  return colors;
}
