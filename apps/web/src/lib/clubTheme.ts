import type { CSSProperties } from 'react';

/**
 * Акцентные переменные страницы клуба, собранные из одного фирменного цвета.
 *
 * Это то самое место, ради которого в tokens.css семантические переменные
 * объявлены переопределяемыми: компонент называет роль («цвет действия»), а не
 * краску, поэтому подмены набора `--accent-*` на обёртке достаточно — ни одна
 * кнопка внутри об этом не знает.
 *
 * Шкала выводится через `color-mix`, а не хранится шестью полями в базе.
 * Шесть полей означали бы шесть возможностей их рассогласовать, а клуб,
 * заполняющий форму настроек, всё равно думает про один свой цвет, а не про
 * оттенок наведения.
 *
 * Тёмная тема отдельно не выводится намеренно: цвет клуба — это его цвет, и
 * подкручивать его под тему значит показывать не тот цвет, который клуб
 * заявил. Читаемость при этом не страдает — по фирменному цвету идёт только
 * текст кнопки, а он берётся из `--accent-text` и остаётся белым.
 *
 * `null` возвращает пустой объект: клуб без своего цвета остаётся в изумруде
 * платформы, и это штатное состояние, а не недоделка.
 */
export function clubAccent(color: string | null | undefined): CSSProperties {
  if (!color || !/^#[0-9a-fA-F]{6}$/.test(color)) {
    return {};
  }

  return {
    '--accent': color,
    // Наведение и нажатие — тот же цвет, подмешанный к чёрному: так шаг
    // остаётся одинаковым для светлого и тёмного фирменного цвета.
    '--accent-hover': `color-mix(in oklab, ${color} 88%, black)`,
    '--accent-active': `color-mix(in oklab, ${color} 76%, black)`,
    // Подложка выделенного раздела и рамка: тот же цвет, разбавленный фоном
    // страницы, поэтому он одинаково работает в обеих темах.
    '--surface-accent-soft': `color-mix(in oklab, ${color} 12%, var(--surface))`,
    '--border-accent': `color-mix(in oklab, ${color} 55%, var(--surface))`,
    // Текст акцентом: подмешан к цвету текста, иначе светло-жёлтый фирменный
    // цвет клуба стал бы нечитаемой надписью на белом.
    '--text-accent': `color-mix(in oklab, ${color} 70%, var(--text))`,
    // Текст НА акценте (кнопка, выбранный зал) — по контрасту с цветом клуба,
    // а не по теме: в тёмной теме токен тёмный под яркий изумруд платформы,
    // и на тёмно-зелёном «Енисее» надпись тонула в заливке.
    '--accent-text': readableOn(color),
  } as CSSProperties;
}

/**
 * Белый или почти чёрный — что контрастнее на этом цвете (по WCAG: светлота
 * цвета против светлоты белого и чёрного).
 */
export function readableOn(color: string): string {
  const channel = (hex: string): number => {
    const value = parseInt(hex, 16) / 255;
    return value <= 0.03928 ? value / 12.92 : ((value + 0.055) / 1.055) ** 2.4;
  };
  const luminance =
    0.2126 * channel(color.slice(1, 3)) + 0.7152 * channel(color.slice(3, 5)) + 0.0722 * channel(color.slice(5, 7));

  return 1.05 / (luminance + 0.05) >= (luminance + 0.05) / 0.05 ? '#ffffff' : 'var(--ink-950)';
}
