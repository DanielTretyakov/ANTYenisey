-- Проверка часового пояса переезжает с клуба на зал.
--
-- Отдельной миграцией, а не правкой предыдущей: та уже применена, и Prisma
-- сверяет контрольные суммы применённых миграций — изменение файла задним
-- числом сломало бы `migrate dev` на любой машине, где он уже прошёл.
--
-- Констрейнт на "Tenant" отдельно снимать не нужно: Postgres удалил его
-- вместе с колонкой "timezone" в предыдущей миграции.

-- Опечатка «Asia/Krasnayarsk» тихо сломает расчёт порога отмены и границ
-- операционного дня ИМЕННО ЭТОГО зала. Приведение к зоне падает с ошибкой на
-- неизвестном имени — этим и проверяем.
--
-- Литерал-константа не случайна: в CHECK допустимы только IMMUTABLE функции,
-- а now() STABLE — с ней Postgres откажется создавать констрейнт.
ALTER TABLE "Hall"
  ADD CONSTRAINT "Hall_timezone_valid"
  CHECK ((TIMESTAMP '2000-01-01 00:00:00' AT TIME ZONE timezone) IS NOT NULL);
