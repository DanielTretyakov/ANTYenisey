-- ФИО переезжает из ClientProfile в User.
--
-- Причина: имя есть у любой роли, а поле лежало только в профиле клиента —
-- тренер оставался безымянным, и публичная карточка тренера из ТЗ не
-- собиралась. У администратора и владельца имени не было вовсе.
--
-- Миграция переносит данные, а не пересоздаёт колонку: у клуба уже заведены
-- клиенты, и терять их ФИО нельзя. Отсюда четыре шага вместо одного.

-- 1. Колонка добавляется допускающей NULL: на существующих строках значения
--    ещё нет, и NOT NULL здесь упал бы.
ALTER TABLE "User" ADD COLUMN "fullName" TEXT;

-- 2. Перенос имён клиентов.
UPDATE "User" AS u
SET "fullName" = c."fullName"
FROM "ClientProfile" AS c
WHERE c."userId" = u."id";

-- 3. Всем остальным (тренеры, администраторы, владелец) имени взять неоткуда —
--    его раньше просто не хранили. Ставим заметный плейсхолдер, чтобы строка
--    не выглядела заполненной: администратор клуба должен её найти и
--    исправить, а не пройти мимо пустого места.
UPDATE "User" SET "fullName" = 'Имя не указано' WHERE "fullName" IS NULL;

-- 4. Теперь колонка заполнена везде и может стать обязательной.
ALTER TABLE "User" ALTER COLUMN "fullName" SET NOT NULL;

-- 5. Старое место освобождается — только после того, как данные перенесены.
ALTER TABLE "ClientProfile" DROP COLUMN "fullName";
