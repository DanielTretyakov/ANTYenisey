-- Телефон и дата рождения обязательны у всех пользователей.
--
-- Раньше телефон был необязателен, а дата рождения лежала только у клиента.
-- И то и другое нужно любой роли: телефон — основной канал связи клуба, дата
-- рождения — детские группы, возрастные турниры и кадровый учёт.
--
-- ВНИМАНИЕ: у уже заведённых сотрудников этих данных нет — их неоткуда взять,
-- и миграция подставляет заметные заглушки. Их видно с первого взгляда
-- (01.01.1900 и +70000000000), и администратор должен их заменить. Молча
-- оставить колонки необязательными было бы хуже: тогда пустые значения
-- продолжали бы появляться и дальше.

-- ---------------------------------------------------------------------------
-- 1. Дата рождения переезжает из ClientProfile в User
-- ---------------------------------------------------------------------------

ALTER TABLE "User" ADD COLUMN "birthDate" DATE;

UPDATE "User" AS u
SET "birthDate" = c."birthDate"
FROM "ClientProfile" AS c
WHERE c."userId" = u."id" AND c."birthDate" IS NOT NULL;

UPDATE "User" SET "birthDate" = DATE '1900-01-01' WHERE "birthDate" IS NULL;

ALTER TABLE "User" ALTER COLUMN "birthDate" SET NOT NULL;

ALTER TABLE "ClientProfile" DROP COLUMN "birthDate";

-- ---------------------------------------------------------------------------
-- 2. Телефон становится обязательным
-- ---------------------------------------------------------------------------

UPDATE "User" SET "phone" = '+70000000000' WHERE "phone" IS NULL;

ALTER TABLE "User" ALTER COLUMN "phone" SET NOT NULL;

-- ---------------------------------------------------------------------------
-- 3. Ограничения целостности
-- ---------------------------------------------------------------------------
--
-- Скопированы из prisma/constraints.sql, раздел 14.

-- Формат E.164 для России. Та же проверка стоит в форме регистрации; здесь она
-- закрывает остальные пути записи — скрипты, импорт клиентской базы,
-- поправленную руками строку.
ALTER TABLE "User"
  ADD CONSTRAINT "User_phone_format"
  CHECK ("phone" ~ '^\+7[0-9]{10}$');

-- Дата рождения в разумных пределах: 1900 год — нижняя граница и заодно
-- заглушка, которую подставила эта миграция. Верхняя — сегодняшний день:
-- родиться завтра нельзя, а опечатка в годе («2062» вместо «2002») иначе
-- прошла бы насквозь и сломала бы возрастные группы.
--
-- CURRENT_DATE в CHECK недопустим — функция не IMMUTABLE, — поэтому верхняя
-- граница задана заведомо будущей датой. Полноту это не даёт, но опечатку в
-- веке ловит; точную проверку делает API.
ALTER TABLE "User"
  ADD CONSTRAINT "User_birth_date_range"
  CHECK ("birthDate" >= DATE '1900-01-01' AND "birthDate" <= DATE '2100-01-01');
