/**
 * Движок бронирования: самостоятельная онлайн-аренда стола клиентом.
 *
 * Первый сценарий ТЗ, который доводит клиента до денег: он сам выбирает
 * стол и время, без подтверждения администратора. Оплата к нему пристроится
 * отдельно — пока бронь заводится со статусом `BOOKED` и посчитанной ценой,
 * но без холда в ЮKassa.
 *
 * Все суммы — **в копейках, целыми числами**, как и везде в контракте.
 */
import type { BookingStep } from './club';

/**
 * Статус брони. Значения совпадают с enum `BookingStatus` из schema.prisma —
 * один и тот же набор у брони стола, тренировки и турнира.
 */
export type BookingStatus = 'BOOKED' | 'CANCELLED' | 'ATTENDED' | 'NO_SHOW';

/**
 * За сколько дней вперёд клиент может занять стол.
 *
 * В ТЗ горизонта нет, и без него бронь уехала бы на год вперёд — на время,
 * под которое расписание ещё даже не составлено, и администратор потом не
 * смог бы отдать этот стол под групповую тренировку.
 *
 * Константа, а не настройка клуба: когда клубам понадобятся разные горизонты,
 * это будет поле в `Tenant` и строка в форме настроек, а до тех пор лишний
 * рычаг только увеличивает число состояний.
 */
export const BOOKING_HORIZON_DAYS = 14;

/** Занятый промежуток в минутах от местной полуночи. */
export interface BusyInterval {
  startMinute: number;
  endMinute: number;
}

/**
 * Стол в сетке доступности на дату.
 *
 * Клиенту отдаётся только «занято», без причины: расписание клуба — его
 * внутренняя кухня, а для выбора времени достаточно знать, что стол не
 * свободен. Занятость склеена из двух источников — расписания зала и уже
 * заведённых броней, — и различать их клиенту тоже незачем.
 */
export interface BookingDayTable {
  tableId: string;
  label: string;
  busy: BusyInterval[];
}

/**
 * Что свободно в зале на конкретную дату.
 *
 * Сетка строится в местном времени клуба: клиент из другого часового пояса
 * должен видеть время зала, а не своё, иначе придёт на два часа раньше.
 */
export interface BookingDay {
  hallId: string;
  /** Календарная дата по времени клуба, «2026-03-12». */
  date: string;
  /** Минимальный шаг брони зала. */
  bookingStep: BookingStep;
  /** Тот же шаг в минутах — чтобы клиент не расшифровывал enum сам. */
  stepMinutes: number;
  /** Границы сетки в минутах от местной полуночи: с 06:00 до полуночи. */
  openMinute: number;
  closeMinute: number;
  /**
   * Минута, раньше которой бронировать уже поздно: на сегодняшней дате это
   * «сейчас», на будущих — начало сетки. Прошедшее время клиент видит
   * недоступным, а не свободным.
   */
  earliestMinute: number;
  /** Есть ли в зале аренда «стол + робот» — от этого зависит сетка цен. */
  hasRobotOption: boolean;
  tables: BookingDayTable[];
}

/**
 * Расчёт стоимости до того, как клиент подтвердил бронь.
 *
 * Цена показывается до нажатия кнопки, а не после: узнать сумму уже после
 * того, как деньги заморожены, — не тот порядок.
 */
export interface BookingQuote {
  durationMinutes: number;
  /**
   * Сколько минут фактически оплачивается. Тарификация идёт начатыми
   * получасами, поэтому 80 минут аренды оплачиваются как 90.
   */
  billedMinutes: number;
  /** Стоимость аренды, копейки. */
  price: number;
}

export interface BookingQuoteQuery {
  hallId: string;
  durationMinutes: number;
  withRobot: boolean;
}

/**
 * Заявка на бронь.
 *
 * Момент начала — в UTC, длительность — числом минут. Не пара «начало и
 * конец»: конец, посчитанный на клиенте, разошёлся бы с шагом зала на первой
 * же ошибке округления, а длительность сервер проверяет по своим правилам.
 */
export interface CreateBookingRequest {
  tableId: string;
  /** Момент начала в ISO-8601 с зоной. */
  startsAt: string;
  durationMinutes: number;
  /** Аренда «стол + робот» — отдельная услуга со своей сеткой цен. */
  withRobot: boolean;
}

/**
 * Бронь в кабинете клиента.
 *
 * Названия зала и стола лежат прямо здесь, а не собираются вторым запросом:
 * список броней открывают, чтобы вспомнить, куда и когда идти, и «стол
 * cljk2f9…» этой задачи не решает.
 */
export interface ClientBooking {
  id: string;
  hallId: string;
  hallName: string;
  tableId: string;
  tableLabel: string;
  /** Моменты в ISO-8601 с зоной; хранятся в UTC. */
  startsAt: string;
  endsAt: string;
  withRobot: boolean;
  /** Стоимость на момент брони, копейки. Позднее изменение прайса её не трогает. */
  price: number;
  status: BookingStatus;
  cancelledAt: string | null;
  /**
   * Сколько процентов списано по факту. Заполняется при отмене и при
   * фиксации неявки; у активной брони пуст.
   */
  chargePercent: number | null;
  /**
   * Сколько спишется, если отменить прямо сейчас, в процентах. Считается по
   * политике клуба от запаса времени до начала. `null` — бронь уже не
   * активна, отменять нечего.
   */
  cancelChargePercentNow: number | null;
}
