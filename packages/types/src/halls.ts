/**
 * Что идёт в каком зале (решение владельца от 25.09.2026): одна организация —
 * залы в разных городах, и виды мероприятий с тренерами у них разные.
 *
 * Привязка хранится списком залов, и ПУСТОЙ СПИСОК — ЭТО «ВО ВСЕХ ЗАЛАХ»: у
 * клуба с одним залом и у видов, заведённых раньше, ничего не ломается, а
 * новый зал сразу получает всё непривязанное.
 *
 * Правило здесь, в общем пакете: по нему сервер проверяет расписание зала, а
 * страница клуба фильтрует тренеров, виды и тарифы. Две копии «пусто — это
 * все» разошлись бы на первой правке.
 */

/** Доступно ли в зале то, что привязано к `linked`. */
export function availableIn(linked: readonly string[], hallId: string): boolean {
  return linked.length === 0 || linked.includes(hallId);
}

/** Доступно ли хотя бы в одном из выбранных залов — фильтр страницы клуба. */
export function availableInAny(linked: readonly string[], hallIds: readonly string[]): boolean {
  return linked.length === 0 || hallIds.some((hallId) => linked.includes(hallId));
}
