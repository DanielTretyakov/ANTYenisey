/**
 * Возраст и возрастные пороги платформы.
 *
 * Одно место на всех: профиль игрока открывается посторонним с 16 лет, опека
 * родителя кончается в 16, родителем становятся с 18, а карточка человека у
 * стойки показывает, сколько ему лет. Раньше полные годы считались в двух
 * местах двумя разными способами, и опека стала бы третьим.
 *
 * Живёт в общем пакете, а не в API: те же годы видит и веб, и расходиться им
 * нельзя — «записывает родитель» не должно висеть на странице, где сервер уже
 * пускает человека записываться самому.
 */

/** С этого дня рождения человек записывается сам и опека родителя кончается. */
export const CHILD_UNTIL_AGE = 16;

/** С этого дня рождения можно закреплять за собой ребёнка. */
export const GUARDIAN_MIN_AGE = 18;

/**
 * Полных лет на сегодня.
 *
 * Календарь — UTC: дата рождения хранится полночью UTC, а у платформы нет
 * одного часового пояса на всех. Порог наступает в день рождения, самое позднее
 * через семь часов по красноярскому времени.
 *
 * Родившийся 29 февраля в невисокосный год становится старше 1 марта: 28
 * февраля его день ещё не наступил.
 */
export function fullYears(birthDate: Date, today: Date): number {
  const years = today.getUTCFullYear() - birthDate.getUTCFullYear();
  const month = today.getUTCMonth() - birthDate.getUTCMonth();
  const passed = month > 0 || (month === 0 && today.getUTCDate() >= birthDate.getUTCDate());

  return passed ? years : years - 1;
}

/**
 * День, когда человеку исполнится `age` лет, — «2029-03-01».
 *
 * У родившегося 29 февраля это 1 марта невисокосного года: `Date.UTC` сам
 * переносит несуществующее 29 февраля на следующий день, и это совпадает с
 * тем, как считает `fullYears`.
 */
export function birthdayOfAge(birthDate: Date, age: number): string {
  return new Date(
    Date.UTC(birthDate.getUTCFullYear() + age, birthDate.getUTCMonth(), birthDate.getUTCDate()),
  )
    .toISOString()
    .slice(0, 10);
}
