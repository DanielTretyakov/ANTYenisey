import type { ClubValue } from './club';
import type { Gender } from './auth';

/**
 * Публичная карточка клуба.
 *
 * Нужна и формам входа/регистрации, и странице клуба: человек не должен
 * вводить и даже видеть технический код клуба («yenisey») — он видит
 * официальное название («АНТ «Енисей»»), а код уходит в запрос сам.
 *
 * Часового пояса здесь больше НЕТ. Он переехал на зал: залы одной организации
 * бывают в разных регионах, и общий на клуб пояс сдвинул бы в одном из них и
 * границы операционного дня, и порог «за час до начала», от которого считаются
 * деньги (ТЗ → «Профиль клуба»). Форме брони пояс приходит вместе с залом.
 */
/** Тренер в составе на странице клуба. Имя сокращено, как везде в открытых списках. */
export interface PublicClubCoach {
  /** Идентификатор учётки — он же адрес карточки `/coaches/:id`. */
  id: string;
  name: string;
  photoFileId: string | null;
  /** Пол — для заглушки, когда фотографии нет. */
  gender: Gender | null;
  /** Цены этого клуба, копейки. Пусто — тренер их не указал. */
  groupPrice: number | null;
  individualPrice: number | null;
  /** Какие занятия тренер ведёт в ближайший месяц — названия типов. */
  leads: string[];
}

export interface PublicTenant {
  /** Технический код, он же Tenant.slug. Уходит в запросы, человеку не показывается. */
  slug: string;
  /** Официальное название клуба для показа человеку. */
  name: string;
  /** Основной город клуба — для карточки и поиска на стартовой странице. */
  city: string | null;
  /** Города залов, отличные от основного: поиск находит клуб и по ним. */
  otherCities: string[];
  /** Логотип организации. Пустой — показывается одно название. */
  logoUrl: string | null;
  /**
   * Фирменный цвет, «#126b54». Страница клуба подменяет им акцент платформы;
   * пустой оставляет её в изумруде «Енисея».
   */
  accentColor: string | null;
  /** Телефон клуба, «+79991234567». Пустой — клуб его не указал. */
  phone: string | null;
  /** Почта клуба. Пустая — то же самое. */
  email: string | null;
  /** Краткое описание клуба. Пусто — клуб его не написал. */
  description: string | null;
  /** Баннер страницы клуба (`GET /files/:id`). Пусто — фирменная плоскость. */
  bannerFileId: string | null;
  /** Ценности клуба карточками под описанием. */
  values: ClubValue[];
  /** Страницы клуба во ВКонтакте и MAX — только https на свой домен. */
  vkUrl: string | null;
  maxUrl: string | null;
  /**
   * Тренерский состав: все действующие тренеры клуба, кроме скрытых
   * администратором; выбранные им — первыми (решение владельца от
   * 25.09.2026). Карточку тренер ведёт сам, цены — клубные.
   */
  coaches: PublicClubCoach[];
  /**
   * Залы клуба: куда ехать и почём стол.
   *
   * Отдаются вместе с карточкой и без всякой авторизации — это и есть ответ на
   * вопросы, с которыми человек приходит на страницу клуба. Цены здесь те же,
   * что посчитает сервер при брони: второй прайс «для витрины» разошёлся бы с
   * настоящим на первой же правке.
   */
  halls: PublicHall[];
}

/** Зал так, как его видит посетитель: где он и сколько стоит час. */
export interface PublicHall {
  id: string;
  name: string;
  city: string | null;
  address: string | null;
  /** Координаты дома для ссылки «На карте»; пусто — карта ищет по адресу. */
  latitude: number | null;
  longitude: number | null;
  /** Цена часа аренды стола без робота, копейки. */
  tableHourPrice: number;
  /** Доплата за каждые следующие 30 минут, копейки. */
  tableExtra30MinPrice: number;
  /** Есть ли в зале аренда с роботом и почём час. */
  robotHourPrice: number | null;
  /** Сколько столов в зале — по ним видно, велик ли зал. */
  tables: number;
}
