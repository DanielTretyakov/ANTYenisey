/**
 * Публичные сведения о клубе.
 *
 * Нужны формам входа и регистрации: человек не должен вводить и даже видеть
 * технический код клуба («yenisey») — он видит официальное название
 * («АНТ «Енисей»»), а код уходит в запрос сам.
 */
export interface PublicTenant {
  /** Технический код, он же Tenant.slug. Уходит в запросы, человеку не показывается. */
  slug: string;
  /** Официальное название клуба для показа человеку. */
  name: string;
}
