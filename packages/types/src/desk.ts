/**
 * Рабочее место администратора: что происходит в зале за один день.
 *
 * Отдельный контракт, а не расширение клиентского `BookingDay`, и разница
 * между ними принципиальная: клиенту отдаётся только «занято», без причины —
 * расписание клуба его внутренняя кухня. Администратору причина и есть суть
 * экрана: он смотрит на зал, чтобы ответить на звонок, а не чтобы выбрать себе
 * время.
 *
 * По той же причине здесь полные имена и телефоны, а не `shortName`.
 * Сокращение защищает публичные списки записавшихся от посторонних, а не клуб
 * от собственного администратора: те же данные он видит в разделе «Состав
 * клуба», и заставлять его открывать карточку ради телефона значит добавить
 * два перехода к каждому звонку.
 *
 * Все суммы — **в копейках, целыми числами**, как и везде в контракте.
 */
import type { BookingStatus } from './booking';
import type { ClosurePurpose } from './club';

/**
 * Где запись по отношению к отметке присутствия.
 *
 * - `UPCOMING` — ещё не началась, отмечать рано;
 * - `ONGOING` — идёт, отмечать уже можно: опоздавшего исправят с причиной;
 * - `AWAITING` — закончилась, напоминание ещё не наступило;
 * - `OVERDUE` — закончилась давно: ТЗ в этот момент шлёт администратору
 *   напоминание. Каналов уведомлений нет, поэтому напоминание — это подсветка на
 *   экране смены.
 *
 * Фазу считает сервер, а не браузер: по часам администратора запись могла бы
 * казаться просроченной, когда джоба ещё не начала на неё смотреть.
 */
export type AttendancePhase = 'UPCOMING' | 'ONGOING' | 'AWAITING' | 'OVERDUE';

/**
 * Вид записи, которую отмечают: аренда стола, запись на занятие, регистрация
 * на турнир. Правила отметки у всех трёх одни, различается только таблица.
 */
export type AttendanceKind = 'TABLE' | 'TRAINING' | 'TOURNAMENT';

/** Итог отметки. «Не отмечено» отметкой не бывает — вернуть в него нельзя. */
export type AttendanceMarkStatus = 'ATTENDED' | 'NO_SHOW';

/**
 * Кто и когда поставил отметку, которая сейчас стоит у записи.
 *
 * Из журнала аудита, а не из самой записи: у записи только текущий статус, а
 * «кто поставил мне неявку» — первый вопрос в споре о деньгах.
 */
export interface DeskMarkInfo {
  /** Кто отметил. `null` — неявку зафиксировала система. */
  by: string | null;
  at: string;
  /** Причина исправления или прощения неявки. */
  reason: string | null;
  /** Неявку поставила джоба автонеявки, а не человек. */
  auto: boolean;
}

/**
 * Правила присутствия клуба — столько, сколько нужно экрану смены, чтобы
 * сказать «списать 100% по политике клуба?» и «система отметит неявку в …».
 */
export interface DeskAttendancePolicy {
  noShowChargePercent: number;
  reminderAfterMinutes: number;
  autoNoShowAfterMinutes: number;
  /** С какого момента клуб ведёт учёт: старшее джоба не трогает. */
  trackedSince: string;
}

/** Человек в списках рабочего места: столько, сколько нужно, чтобы позвонить. */
export interface DeskPerson {
  userId: string;
  fullName: string;
  /**
   * Телефон в E.164. Не пустой: в схеме он обязателен для всех ролей — это
   * основной канал связи клуба и с клиентом, и с сотрудником.
   */
  phone: string;
}

/**
 * Чем занят стол в конкретный момент.
 *
 * Источник различается намеренно: за бронью стоит человек, который заплатит,
 * а за окном расписания — план самого клуба. Освободить второе администратор
 * вправе, первое — уже чужая договорённость.
 */
export interface DeskTableBusy {
  source: 'BOOKING' | 'SCHEDULE';
  /** Назначение окна. У брони стола это всегда аренда. */
  purpose: ClosurePurpose;
  /** Кто за столом: клиент брони, тренер занятия или закреплённый арендатор. */
  person: string | null;
  /** До какой минуты местных суток занято. */
  untilMinute: number;
}

/** Состояние одного стола на момент запроса. */
export interface DeskTableNow {
  tableId: string;
  label: string;
  /** Чем занят прямо сейчас; `null` — свободен. */
  busy: DeskTableBusy | null;
  /**
   * С какой минуты стол будет занят в следующий раз.
   *
   * У свободного стола это ответ на вопрос «до скольки он свободен», у
   * занятого — «есть ли за этой занятостью следующая». `null` — до конца дня
   * больше ничего.
   */
  nextFromMinute: number | null;
}

/**
 * Аренда стола в ленте дня.
 *
 * Отдельно от мероприятий, а не одним списком с ними: за бронью стоит один
 * человек, а за занятием — состав из десяти, и общая форма потеряла бы либо
 * телефон одного, либо список остальных. Свести их по времени — задача
 * показа, и она решается на странице.
 */
export interface DeskBooking {
  id: string;
  tableId: string;
  tableLabel: string;
  hallId: string;
  startsAt: string;
  endsAt: string;
  withRobot: boolean;
  /** Стоимость на момент брони, копейки. */
  price: number;
  status: BookingStatus;
  client: DeskPerson;
  /** Зал брони: в списке «Требует отметки» лежат брони всех залов клуба. */
  hallName: string;
  /**
   * Бронь завёл администратор, а не клиент сам.
   *
   * Показывается меткой в ленте: «завёл админ» объясняет, почему человек не
   * видит её в приложении и почему звонить о переносе будут в клуб.
   */
  manual: boolean;
  /** Кто из сотрудников завёл. Пусто у самостоятельной онлайн-брони. */
  createdBy: string | null;
  /** Момент отмены и сколько с клиента списано по политике клуба. */
  cancelledAt: string | null;
  /** Процент списания: по политике отмены, 100 у пришедшего, процент неявки. */
  chargePercent: number | null;
  phase: AttendancePhase;
  /** Когда система сама зафиксирует неявку; `null` — не зафиксирует. */
  autoNoShowAt: string | null;
  /** Кто поставил нынешнюю отметку. У неотмеченной — `null`. */
  mark: DeskMarkInfo | null;
}

/**
 * Заявка администратора на бронь для другого человека.
 *
 * Отличается от клиентской `CreateBookingRequest` ровно одним полем —
 * `clientId`. Отдельный тип, а не расширение: у клиентской заявки этого поля
 * не должно быть даже опционально, иначе однажды кто-нибудь пришлёт её с чужим
 * идентификатором на клиентский маршрут.
 */
export interface CreateDeskBookingRequest {
  /** Кого сажаем. Человек может ещё не состоять в клубе — привязка заведётся. */
  clientId: string;
  tableId: string;
  /** Момент начала в ISO-8601 с зоной. */
  startsAt: string;
  durationMinutes: number;
  withRobot: boolean;
}

/**
 * Перенос брони: другой стол, другое время или другая длительность.
 *
 * Именно перенос, а не «отменить и создать заново». Отмена зафиксировала бы
 * процент списания и испортила клиенту статистику отмен — за то, что стол
 * переставил администратор.
 */
export interface MoveDeskBookingRequest {
  tableId: string;
  startsAt: string;
  durationMinutes: number;
}

/** Отмена брони администратором. */
export interface CancelDeskBookingRequest {
  /**
   * Простить списание: клуб виноват — сломался стол, отменили занятие.
   *
   * Без этого администратору осталось бы только звонить в бухгалтерию:
   * процент считается по политике клуба от запаса времени, и «мы сами
   * виноваты» в неё не заложено.
   */
  waiveCharge?: boolean;
}

/** Записавшийся на занятие или турнир. */
export interface DeskParticipant extends DeskPerson {
  /**
   * Идентификатор самой записи, а не человека.
   *
   * Им отмечается присутствие: у одного человека на одном занятии запись
   * ровно одна, но искать её сервером заново по паре «человек + занятие»
   * значило бы повторить на записи присутствия ту же выборку, которая уже
   * сделана здесь.
   */
  entryId: string;
  status: BookingStatus;
  chargePercent: number | null;
  mark: DeskMarkInfo | null;
}

/**
 * Занятие или турнир в ленте дня — с полным составом.
 *
 * Состав приезжает сразу, а не по нажатию: администратор открывает экран
 * смены именно затем, чтобы увидеть, кого ждать, и второй запрос на каждое
 * занятие превратил бы это в десяток походов к серверу.
 */
export interface DeskEvent {
  id: string;
  kind: 'TRAINING' | 'TOURNAMENT';
  title: string;
  startsAt: string;
  endsAt: string;
  /** Цена участия на момент показа, копейки. */
  price: number;
  /** Лимит мест. У турнира его нет вовсе. */
  capacity: number | null;
  /** Тренер занятия. У турнира отсутствует. */
  coachName: string | null;
  participants: DeskParticipant[];
  phase: AttendancePhase;
  autoNoShowAt: string | null;
}

/**
 * Деньги за день — НАЧИСЛЕННЫЕ, а не полученные.
 *
 * Платёжного шлюза в системе нет: `Payment` не пишется ниоткуда, и сумма
 * складывается из копий цен на момент записи. Это стоимость оказанных услуг,
 * а не касса, и называть её выручкой нельзя — администратор сверит с ящиком в
 * первый же вечер и перестанет верить экрану.
 *
 * Разбивка важнее итога: итог сам по себе ни о чём не говорит, а «турниров на
 * 12 000» объясняет, почему день такой.
 */
export interface DeskMoney {
  /** Аренда столов, копейки. */
  tables: number;
  trainings: number;
  tournaments: number;
  total: number;
  /**
   * Сколько человек придёт: записи в статусах «записан» и «пришёл».
   *
   * Отменённые и неявки не считаются — они дают деньги, но не дают людей в
   * зале, а число визитов админ читает как «сколько сегодня народу».
   */
  count: number;
  /**
   * Сколько начислено по отменённым записям — по политике отмены клуба.
   *
   * Входит в `total`: поздняя отмена приносит клубу деньги, и не показать их
   * значило бы занизить день. Отдельной строкой, потому что это единственная
   * часть суммы, за которой никто не пришёл.
   */
  cancelled: number;
}

/** Занятость зала в один час: сколько столов занято хотя бы частично. */
export interface DeskLoadHour {
  /** Час местных суток, 0..23. */
  hour: number;
  busyTables: number;
}

/**
 * Один день зала глазами администратора.
 *
 * Собирается одним запросом, а не тремя: экран открывают по двадцать раз за
 * смену, и три ожидания вместо одного — умножение задержки на ровном месте.
 */
export interface DeskDay {
  hallId: string;
  hallName: string;
  /** Календарная дата по времени ЗАЛА, «2026-03-12». */
  date: string;
  /** Часовой пояс зала. Залы одного клуба бывают в разных регионах. */
  timezone: string;
  /** Совпадает ли запрошенная дата с сегодняшней по времени зала. */
  today: boolean;
  /**
   * Который сейчас час в зале, в минутах от местной полуночи.
   *
   * `null`, когда смотрят не сегодняшний день: «сейчас» у прошлой субботы не
   * существует, и рисовать на ней текущий момент значило бы соврать.
   */
  nowMinute: number | null;
  /** Границы сетки в минутах от местной полуночи. */
  openMinute: number;
  closeMinute: number;

  tables: DeskTableNow[];
  bookings: DeskBooking[];
  events: DeskEvent[];
  load: DeskLoadHour[];
  money: DeskMoney;

  policy: DeskAttendancePolicy;
  /**
   * Что ждёт отметки — по всему клубу, а не только в этом зале и в этот день.
   *
   * Вчерашнее неотмеченное и мероприятие, заведённое не в сетке, в ленту дня
   * не попадают — и без общего списка их не отметил бы никто, кроме джобы. Плюс
   * неотмеченное этого дня, даже если оно старше начала учёта.
   */
  pending: { bookings: DeskBooking[]; events: DeskEvent[] };
  /** Визиты с порога в этот день — по всему клубу: у визита нет зала. */
  visits: DeskVisit[];
}

/** Отметка одной записи. */
export interface MarkAttendanceRequest {
  status: AttendanceMarkStatus;
  /** Обязательна при исправлении уже поставленной отметки и при прощении. */
  reason?: string;
  /** Неявка без списания: клиент не пришёл по вине клуба. */
  waiveCharge?: boolean;
}

/** «Отметить всех пришедшими» — одной транзакцией. */
export interface MarkAttendanceBatchRequest {
  marks: (MarkAttendanceRequest & { kind: AttendanceKind; entryId: string })[];
}

/** Что стало с записью после отметки. */
export interface AttendanceResult {
  kind: AttendanceKind;
  entryId: string;
  status: BookingStatus;
  chargePercent: number | null;
  /** `false` — запись уже была в этом состоянии, в журнал ничего не легло. */
  changed: boolean;
}

/** Строка истории отметок записи — для спора с клиентом. */
export interface AttendanceHistoryItem {
  at: string;
  /** Кто действовал; `null` — система. */
  by: string | null;
  auto: boolean;
  before: { status: BookingStatus; chargePercent: number | null } | null;
  after: { status: BookingStatus; chargePercent: number | null } | null;
  reason: string | null;
}

/**
 * Визит с порога или внесённый задним числом.
 *
 * Один инструмент на оба случая, как в ТЗ: человек пришёл без брони — или
 * играл, а записать забыли. Денег визит не двигает.
 */
export interface RecordVisitRequest {
  clientId: string;
  /** Момент визита в ISO-8601 с зоной. Не в будущем. */
  visitedAt: string;
  coachId?: string;
  note?: string;
}

export interface DeskVisit {
  id: string;
  client: DeskPerson;
  visitedAt: string;
  coachName: string | null;
  note: string | null;
  recordedBy: string | null;
}
