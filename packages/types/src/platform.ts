/**
 * Контракт платформенного уровня — того, что выше отдельного клуба.
 *
 * Сюда попадает всё, у чего клуба нет или у чего клубов несколько: справочник
 * городов, поиск клубов, «мои клубы» и записи человека по всем клубам сразу.
 * Клубные маршруты живут в club.ts и booking.ts.
 */

import type { BookingStatus } from './booking';

/**
 * Город из справочника платформы.
 *
 * Справочник, а не строка в карточке клуба: свободный ввод даёт «Красноярск»,
 * «г. Красноярск» и «краснярск» тремя разными городами, и поиск по городу
 * перестаёт работать (ТЗ → «Профиль клуба»).
 */
export interface City {
  id: string;
  name: string;
  /** Регион — чтобы различить одноимённые города. Может отсутствовать. */
  region: string | null;
}

/** Ссылка на клуб: минимум, которого хватает, чтобы его назвать и открыть. */
export interface ClubRef {
  /** Код клуба — он же участок адреса: /clubs/:slug */
  slug: string;
  name: string;
  /** Фирменный цвет, «#126b54». Пустой — страница остаётся в цветах платформы. */
  accentColor: string | null;
}

/** Карточка клуба в результатах поиска и в списке «моих клубов». */
export interface ClubCard extends ClubRef {
  logoUrl: string | null;
  /** Основной город клуба — тот, что показывается в карточке. */
  city: string | null;
  /**
   * Города залов, отличные от основного.
   *
   * Показываются отдельной строкой, потому что поиск по городу находит клуб и
   * по ним тоже: клуб с залами в Красноярске и Абакане иначе выглядел бы в
   * выдаче Абакана ошибкой.
   */
  otherCities: string[];
  /** Сколько залов у клуба — грубая мера размера, без похода за списком. */
  hallCount: number;
}

/** Что спрашивает стартовая страница у поиска клубов. */
export interface ClubSearchQuery {
  /** Часть названия клуба. */
  query?: string;
  cityId?: string;
}

/**
 * Отметка «мой клуб».
 *
 * Избранное и заявленная принадлежность — ОДНА сущность, а не две (ТЗ → «Мои
 * клубы»): разделять их значило бы объяснять человеку разницу, которой в его
 * голове нет. Отсюда и предел в три клуба.
 */
export interface FavouriteClub extends ClubCard {
  /**
   * Занятое место, 1..3. Человеку не показывается — им предел выражен в базе:
   * четвёртый клуб физически некуда положить.
   */
  slot: number;
}

/** Сколько клубов человек может отметить своими. */
export const MAX_FAVOURITE_CLUBS = 3;

/** Чем человек занят: аренда стола или участие в турнире. */
export type BookingKind = 'TABLE' | 'TOURNAMENT';

/**
 * Одна запись человека — в разделе «Мои записи» и в блоке «Мои мероприятия»
 * на странице клуба.
 *
 * Тип ОДИН на оба списка намеренно. Два разных списка записей в двух местах
 * разошлись бы в поведении отмены и в том, что каждый из них показывает, —
 * ровно то, от чего ТЗ предостерегает, требуя убрать список записей из
 * кабинета целиком.
 */
export interface BookingEntry {
  /** Идентификатор брони стола либо турнира, на который человек записан. */
  id: string;
  kind: BookingKind;
  /** Клуб записи. На странице клуба он и так известен, но список по всем клубам без него не собрать. */
  club: ClubRef;
  /** «Аренда стола» либо название типа турнира. */
  title: string;
  /** Зал и стол для аренды; для турнира — пусто. */
  subtitle: string | null;
  startsAt: string;
  /** У турнира окончание не задано — в схеме у него только момент начала. */
  endsAt: string | null;
  /** Копейки. Цена зафиксирована на момент записи. */
  price: number;
  status: BookingStatus;
  /** Сколько списано при отмене. Пусто, пока запись жива. */
  chargePercent: number | null;
  /**
   * Сколько спишется, если отменить прямо сейчас. Вопрос, на который человек
   * должен получить ответ ДО нажатия кнопки, а не после.
   */
  cancelChargePercentNow: number | null;
}

/**
 * Мероприятие в открытом списке клуба.
 *
 * Аренды столов здесь нет и быть не может (ТЗ → «Страница клуба»): к чужой
 * броне стола нельзя присоединиться, и публичный список из неё состоял бы из
 * строк, на которые невозможно записаться.
 */
export interface ClubEvent {
  /** Tournament.id — по нему идёт запись. */
  id: string;
  /** Название типа турнира. */
  title: string;
  /**
   * Справочное число-ограничение по рейтингу из названия типа («100» у «Клуб
   * 100»). Система его не проверяет и регистрацию не блокирует.
   */
  ratingLabel: string | null;
  startsAt: string;
  /** Цена участия, копейки. */
  price: number;
  registeredCount: number;
  /**
   * Записан ли спрашивающий. `null` — спрашивает аноним: список открыт без
   * входа, и отвечать «не записан» человеку, который просто не представился,
   * значило бы показать ему кнопку записи, которая приведёт на форму входа.
   */
  registered: boolean | null;
}

/** Лента ближайших мероприятий моих клубов на стартовой странице. */
export interface FeedEvent extends ClubEvent {
  club: ClubRef;
}
