/**
 * Контракт платформенного уровня — того, что выше отдельного клуба.
 *
 * Сюда попадает всё, у чего клуба нет или у чего клубов несколько: справочник
 * городов, поиск клубов, «мои клубы» и записи человека по всем клубам сразу.
 * Клубные маршруты живут в club.ts и booking.ts.
 */

import type { BookingStatus } from './booking';
import type { PaidBySubscription } from './subscription';
import type { Gender } from './auth';

/**
 * Город из справочника платформы.
 *
 * Справочник, а не строка в карточке клуба: свободный ввод даёт «Красноярск»,
 * «г. Красноярск» и «краснярск» тремя разными городами, и поиск по городу
 * перестаёт работать (ТЗ → «Профиль клуба»).
 */
export interface City {
  id: string;
  name: string;
  /** Регион — чтобы различить одноимённые города. Может отсутствовать. */
  region: string | null;
}

/** Подсказки города: начало названия и сколько подсказок отдать (до 50). */
export interface CitySearchQuery {
  query?: string;
  limit?: number;
}

/** Ссылка на клуб: минимум, которого хватает, чтобы его назвать и открыть. */
export interface ClubRef {
  /** Код клуба — он же участок адреса: /clubs/:slug */
  slug: string;
  name: string;
  /** Фирменный цвет, «#126b54». Пустой — страница остаётся в цветах платформы. */
  accentColor: string | null;
}

/** Карточка клуба в результатах поиска и в списке «моих клубов». */
export interface ClubCard extends ClubRef {
  logoUrl: string | null;
  /** Основной город клуба — тот, что показывается в карточке. */
  city: string | null;
  /**
   * Города залов, отличные от основного.
   *
   * Показываются отдельной строкой, потому что поиск по городу находит клуб и
   * по ним тоже: клуб с залами в Красноярске и Абакане иначе выглядел бы в
   * выдаче Абакана ошибкой.
   */
  otherCities: string[];
  /** Сколько залов у клуба — грубая мера размера, без похода за списком. */
  hallCount: number;
}

/** Что спрашивает стартовая страница у поиска клубов. */
export interface ClubSearchQuery {
  /** Часть названия клуба. */
  query?: string;
  cityId?: string;
}

/**
 * Отметка «мой клуб».
 *
 * Избранное и заявленная принадлежность — ОДНА сущность, а не две (ТЗ → «Мои
 * клубы»): разделять их значило бы объяснять человеку разницу, которой в его
 * голове нет. Отсюда и предел в три клуба.
 */
export interface FavouriteClub extends ClubCard {
  /**
   * Занятое место, 1..3. Человеку не показывается — им предел выражен в базе:
   * четвёртый клуб физически некуда положить.
   */
  slot: number;
}

/** Сколько клубов человек может отметить своими. */
export const MAX_FAVOURITE_CLUBS = 3;

/** Чем человек занят: аренда стола, занятие или участие в турнире. */
export type BookingKind = 'TABLE' | 'TRAINING' | 'TOURNAMENT';

/**
 * Мероприятие, на которое можно записаться, — занятие или турнир.
 *
 * Аренда стола сюда не входит: к чужой броне стола нельзя присоединиться.
 * Отдельный тип от `BookingKind` именно поэтому, а не ради красоты — на нём
 * стоят открытые списки клуба, куда аренде хода нет.
 */
export type EventKind = Exclude<BookingKind, 'TABLE'>;

/**
 * Одна запись человека — в разделе «Мои записи» и в блоке «Мои мероприятия»
 * на странице клуба.
 *
 * Тип ОДИН на оба списка намеренно. Два разных списка записей в двух местах
 * разошлись бы в поведении отмены и в том, что каждый из них показывает, —
 * ровно то, от чего ТЗ предостерегает, требуя убрать список записей из
 * кабинета целиком.
 */
export interface BookingEntry {
  /**
   * Идентификатор брони стола либо мероприятия, на которое человек записан
   * (занятия или турнира) — не строки записи: по нему идёт отмена.
   */
  id: string;
  /**
   * Идентификатор самой строки записи.
   *
   * У мероприятия он не совпадает с `id`: человек, отменивший запись и
   * записавшийся снова, имеет на одном занятии две строки — отменённую и
   * живую, — и `id` у них один. Ключ списка и поиск «та самая запись» идут по
   * этому полю, иначе React склеит две строки в одну, а ответ на запись
   * покажет старую отменённую.
   */
  entryId: string;
  kind: BookingKind;
  /** Клуб записи. На странице клуба он и так известен, но список по всем клубам без него не собрать. */
  club: ClubRef;
  /** «Аренда стола» либо название типа турнира. */
  title: string;
  /** Зал и стол для аренды, тренер для занятия; для турнира — пусто. */
  subtitle: string | null;
  startsAt: string;
  endsAt: string;
  /** Копейки. Цена зафиксирована на момент записи. */
  price: number;
  status: BookingStatus;
  /**
   * Сколько списано: при отмене — по политике отмены, при отметке — 100 у
   * пришедшего, процент клуба у неявки, 0 у прощённой. Пусто, пока запись
   * ждёт.
   */
  chargePercent: number | null;
  /**
   * Можно ли отменить запись прямо сейчас — решает сервер.
   *
   * После начала запись не отменяется, а отмечается клубом: иначе пропустивший
   * занятие отменял бы его задним числом и платил позднюю отмену вместо
   * неявки. Браузеру эту границу не пересчитывать: его часы — не часы клуба.
   */
  cancellable: boolean;
  /**
   * Сколько спишется, если отменить прямо сейчас. Вопрос, на который человек
   * должен получить ответ ДО нажатия кнопки, а не после.
   *
   * У записи по абонементу — пусто: денег она не стоит, вместо процента
   * отвечает `cancelOutcome`.
   */
  cancelChargePercentNow: number | null;
  /** Абонемент, которым оплачена запись. Пусто — запись по цене. */
  paidBy: PaidBySubscription | null;
  /**
   * Что будет с визитом абонемента, если отменить прямо сейчас: вернётся или
   * сгорит (строгое правило клуба и поздняя отмена). Пусто у записи по цене и
   * у той, что уже нельзя отменить.
   */
  cancelOutcome: 'REFUND' | 'BURN' | null;
}

/**
 * Мероприятие в открытом списке клуба.
 *
 * Аренды столов здесь нет и быть не может (ТЗ → «Страница клуба»): к чужой
 * броне стола нельзя присоединиться, и публичный список из неё состоял бы из
 * строк, на которые невозможно записаться.
 */
export interface ClubEvent {
  /** Tournament.id либо TrainingSession.id — по нему идёт запись. */
  id: string;
  /**
   * Занятие или турнир. Маршрут записи у них разный, и веб выбирает его
   * отсюда: у турнира и занятия могут совпасть даже названия («Первая подача»
   * есть и там, и там), а по идентификатору вид не восстановить.
   */
  kind: EventKind;
  /**
   * Тип занятия или турнира — по нему страница клуба фильтрует список
   * («только детские тренировки»). Уникален вместе с `kind`.
   */
  typeId: string;
  /** Название типа тренировки либо типа турнира. */
  title: string;
  /**
   * Справочное число-ограничение по рейтингу из названия типа («100» у «Клуб
   * 100»). Система его не проверяет и регистрацию не блокирует. У занятия
   * всегда пусто.
   */
  ratingLabel: string | null;
  startsAt: string;
  endsAt: string;
  /** Тренер занятия. У турнира пусто. */
  subtitle: string | null;
  /** Цена участия, копейки. */
  price: number;
  /**
   * Чем будет оплачена запись того, кто смотрит (или за кого он действует):
   * абонементом — или пусто, тогда по цене. Подсказка, а не обещание: выбор
   * делается в момент записи, и если визиты за это время кончатся, запись
   * пойдёт по цене.
   */
  payWith: PaidBySubscription | null;
  registeredCount: number;
  /**
   * Лимит мест и остаток. У ТУРНИРА ОБА ПУСТЫ, и это не недоделка: в схеме
   * `Tournament` несёт только дату и тип, лимита мест у него нет, а число
   * записавшихся показывается справочно.
   */
  capacity: number | null;
  freeSeats: number | null;
  /**
   * Записавшиеся в формате «Фамилия И.» — требование ТЗ, и видит их любой
   * пользователь, а не только записавшийся. Фамилия с инициалом, а не полное
   * имя: список посетителей клуба — персональные данные, и показывать больше
   * необходимого незачем.
   */
  participants: string[];
  /**
   * Записан ли спрашивающий. `null` — спрашивает аноним: список открыт без
   * входа, и отвечать «не записан» человеку, который просто не представился,
   * значило бы показать ему кнопку записи, которая приведёт на форму входа.
   */
  registered: boolean | null;
}

/**
 * Что вообще есть в клубе: действующий тип занятия или турнира — вкладка
 * «Мероприятия клуба» (решение владельца от 25.09.2026). Не проведение, а
 * вид: «Детская тренировка», «Клуб 100».
 */
export interface ClubCatalogItem {
  kind: EventKind;
  typeId: string;
  name: string;
  description: string | null;
  /** Цена участия, копейки. */
  price: number;
  /** Справочная планка рейтинга турнира; у занятия пусто. */
  ratingLabel: string | null;
  /** Ближайшее проведение; пусто — в расписании его пока нет. */
  nextStartsAt: string | null;
  /** Сколько проведений впереди. */
  upcomingCount: number;
  /** Залы, где идёт; пусто — во всех. По ним фильтрует страница клуба. */
  hallIds: string[];
}

/** Лента ближайших мероприятий моих клубов на стартовой странице. */
export interface FeedEvent extends ClubEvent {
  club: ClubRef;
}

/**
 * Записавшийся в окне мероприятия.
 *
 * `userId` и аватар пусты у игрока младше 14: его профиль посторонним закрыт
 * (404), и кружок со ссылкой вёл бы в никуда, а фотография ребёнка в открытом
 * списке — ровно то, что закрытый профиль и прячет. Имя сокращено всегда.
 */
export interface EventParticipant {
  userId: string | null;
  name: string;
  avatarFileId: string | null;
  /** Пол для заглушки; у игрока младше 14 пуст — как и всё остальное о нём. */
  gender: Gender | null;
}

/** Где проходит мероприятие. Выводится из окна расписания, иначе неизвестно. */
export interface EventPlace {
  hallName: string;
  city: string | null;
  address: string | null;
  /** Телефон зала — кому звонить про это мероприятие; пусто — клуба. */
  phone: string | null;
}

/**
 * Мероприятие для окна подробностей: строка списка плюс то, что в список не
 * помещается.
 *
 * Отдельным ответом, а не полями `ClubEvent`: список клуба отдаёт все
 * предстоящие проведения сразу, и таскать в каждом описание, адрес и аватары
 * всех записавшихся значило бы платить за окно, которое откроют у одного.
 */
export interface EventDetail extends ClubEvent {
  club: ClubRef;
  /** Описание типа занятия или турнира — пишет клуб в «Занятиях и турнирах». */
  description: string | null;
  /**
   * Зал с адресом. Пусто, когда мероприятие заведено без окна в сетке зала:
   * связь «мероприятие → зал» в схеме есть только через расписание.
   */
  place: EventPlace | null;
  /** Тренер занятия со ссылкой на публичную карточку. У турнира пусто. */
  coach: { id: string; name: string } | null;
  people: EventParticipant[];
}
