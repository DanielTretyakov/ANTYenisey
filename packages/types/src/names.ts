/**
 * Сокращение ФИО до «Фамилия И.».
 *
 * Формат взят из ТЗ: в списке записавшихся на занятие или турнир человек видит
 * именно «Фамилия И.». Список посетителей клуба — персональные данные, и
 * показывать больше необходимого незачем.
 *
 * Живёт в общем пакете, а не в вебе, потому что сокращает теперь обе стороны:
 * сервер отдаёт состав записавшихся уже сокращённым (полные имена чужих людей
 * не должны уходить в браузер вовсе), а веб теми же буквами подписывает
 * тренера в клетке расписания. Две копии этой функции разошлись бы на первом
 * же человеке с двойной фамилией.
 */
export function shortName(fullName: string): string {
  const parts = fullName.trim().split(/\s+/).filter(Boolean);

  if (parts.length === 0) {
    return '';
  }

  const [surname, firstName] = parts;

  // Одно слово — отдаём как есть: инициал брать неоткуда, а обрезать фамилию
  // до буквы значит потерять единственное, что различает людей.
  if (!firstName) {
    return surname!;
  }

  return `${surname} ${firstName[0]!.toUpperCase()}.`;
}
