/**
 * Ответ на поиск человека на платформе по точной почте или телефону.
 *
 * Поиск ТОЧНЫЙ и только по одному полю: частичное совпадение позволило бы
 * администратору листать людей чужих клубов, а это чужие персональные данные.
 * Здесь он ищет того, кто стоит перед ним и назвал свою почту.
 *
 * Пока человек не в клубе, имя отдаётся сокращённым — «Иванов И.». Этого
 * хватает, чтобы убедиться, что нашёлся нужный, и мало, чтобы собирать чужую
 * базу перебором адресов.
 */
export interface PlatformPersonLookup {
  found: boolean;
  /**
   * Совпало несколько человек — так бывает только с телефоном: почта на
   * платформе уникальна, а телефон нет. Семья с одним номером на всех —
   * обычное дело, и выбрать за администратора, кто из них нужен, нельзя.
   * Тогда `person` пуст, а искать надо по почте.
   */
  ambiguous: boolean;
  person: {
    id: string;
    /** «Иванов И.» до привязки, полное имя — когда человек уже в клубе. */
    name: string;
    /** Состоит ли он в этом клубе уже сейчас. */
    member: boolean;
  } | null;
}
