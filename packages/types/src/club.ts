/**
 * Профиль клуба — то, что владелец и администратор настраивают сами, без
 * участия разработчика (ТЗ → «Профиль клуба»).
 *
 * Все суммы — **в копейках, целыми числами**. Рубли с дробной частью в этот
 * контракт не попадают ни разу: 0.1 + 0.2 в двоичной плавающей точке даёт
 * 0.30000000000000004, и на длинной аренде такая копейка расходится с кассой.
 * Перевод в рубли — только на границе показа человеку.
 *
 * Настройки разделены надвое. У **клуба** — то, что составляет договор с
 * клиентом: название, часовой пояс, политика неявки, правила абонемента.
 * У **зала** — то, что различается между помещениями: цены и шаг брони.
 */
import type { Role } from './auth';

/**
 * Минимальный шаг брони стола. Набор закрытый: зал выбирает из вариантов,
 * а не вводит число, — произвольный шаг вроде 7 минут ломает и сетку
 * расписания, и расчёт цены.
 *
 * Значения совпадают с enum `BookingStep` из schema.prisma — при добавлении
 * шага править оба места.
 */
export type BookingStep = 'MIN_10' | 'MIN_15' | 'MIN_20' | 'MIN_30' | 'HOUR_1';

/** Настройки клуба: общие для всех его залов. */
export interface ClubSettings {
  /** Официальное название клуба — то, что видит клиент. */
  name: string;
  /**
   * Часовой пояс клуба (IANA, напр. «Asia/Krasnoyarsk»). Не косметика: от него
   * зависят пороги отмены, границы операционного дня и то, какой календарной
   * дате принадлежит расписание.
   */
  timezone: string;

  /** Сколько списать с клиента, который не отменил и не пришёл, в процентах. */
  noShowChargePercent: number;
  /** Через сколько минут после мероприятия напомнить админу отметить присутствие. */
  attendanceReminderAfterMinutes: number;
  /** Через сколько минут зафиксировать неявку автоматически. Строго больше напоминания. */
  attendanceAutoNoShowAfterMinutes: number;
  /** Визит абонемента сгорает только при неявке, а при отмене возвращается. */
  subscriptionBurnsOnNoShowOnly: boolean;
}

/**
 * Правка настроек. Все поля необязательны: форма шлёт только изменённое, а
 * перекрёстные проверки сервер делает уже на слитом состоянии.
 */
export type UpdateClubSettingsRequest = Partial<ClubSettings>;

/**
 * Зал: помещение со своим набором столов и своей ценой.
 *
 * Залы различаются тем, что стоит денег, — оборудованием, размером, наличием
 * роботов. Поэтому цены и шаг брони здесь, а не на клубе.
 */
export interface Hall {
  id: string;
  name: string;

  bookingStep: BookingStep;
  /** Цена первого часа аренды стола без робота, копейки. */
  tableHourPrice: number;
  /** Доплата за каждые следующие 30 минут без робота, копейки. */
  tableExtra30MinPrice: number;

  // Аренда «стол + робот»: отдельная услуга со своей сеткой цен, а не
  // наценка поверх обычной аренды (ТЗ → «Пользовательские сценарии»).
  hasRobotOption: boolean;
  /** Копейки. Обязательны, когда `hasRobotOption` включена, иначе null. */
  robot30MinPrice: number | null;
  robot60MinPrice: number | null;
  robotExtra30MinPrice: number | null;
}

export type CreateHallRequest = Omit<Hall, 'id'>;
export type UpdateHallRequest = Partial<CreateHallRequest>;

/**
 * Стол зала.
 *
 * «Настройка количества столов» из ТЗ — это добавление и удаление строк, а не
 * поле со счётчиком: счётчик рядом с реальными столами неизбежно разошёлся бы
 * с ними.
 */
export interface ClubTable {
  id: string;
  hallId: string;
  /** Название, которое видит клиент: «Стол 1», «Стол у окна». Уникально в зале. */
  label: string;
  /**
   * Есть ли у стола брони. Стол с историей удалить нельзя — за бронями висят
   * платежи, нужные бухгалтерии.
   */
  hasBookings: boolean;
  /**
   * Сколько окон занятого времени на столе — в шаблоне недели и в расписаниях
   * дней. Удаление стола унесёт их с собой, поэтому число показывается
   * администратору до того, как он нажмёт «Удалить».
   */
  closureCount: number;
}

export interface CreateTableRequest {
  hallId: string;
  label: string;
}

export interface RenameTableRequest {
  label: string;
}

/**
 * Почему стол недоступен для самостоятельной онлайн-брони.
 *
 * Клиент видит только то, что время занято; расшифровка нужна персоналу клуба
 * и статистике. Значения совпадают с enum `ClosurePurpose` из schema.prisma.
 */
export type ClosurePurpose =
  | 'RENT'
  | 'SPARRING'
  | 'TRAINING'
  | 'ROBOT'
  | 'TOURNAMENT'
  | 'OTHER';

/**
 * День недели по ISO-8601: 1 — понедельник, 7 — воскресенье.
 *
 * Ноль как обозначение дня запрещён намеренно: в разных языках он означает то
 * воскресенье, то понедельник, и одно такое значение тихо сдвинуло бы всё
 * расписание на день.
 */
export type Weekday = 1 | 2 | 3 | 4 | 5 | 6 | 7;

/** Занятое время стола — общая часть шаблона недели и расписания дня. */
export interface ClosureSlot {
  tableId: string;
  /**
   * Границы окна в минутах от полуночи **по времени клуба**, а не в UTC:
   * «каждый вторник с 15:00» не должно зависеть от того, какому мгновению UTC
   * это соответствует. Полночь как конец окна — 1440, а не 0.
   */
  startMinute: number;
  endMinute: number;
  purpose: ClosurePurpose;
  /**
   * Тренер, ведущий занятие. Обязателен при `purpose: 'TRAINING'` — иначе
   * проведённая тренировка не попадёт в его статистику. Допустим ещё у
   * спарринга; для аренды, робота и прочего запрещён.
   */
  coachId: string | null;
  /**
   * Клиент, за которым закреплено время: арендатор стола или тот, кто взял
   * робота. Необязателен — стол можно занять под аренду до того, как известно,
   * кто придёт. Для тренировки и спарринга запрещён: там участников много, и
   * один «закреплённый» ввёл бы в заблуждение.
   */
  clientId: string | null;
  /**
   * Какая это тренировка: «Общая групповая», «Первая подача». Обязателен при
   * `purpose: 'TRAINING'` — от типа зависит цена, а «просто тренировка» в
   * расписании не говорит клиенту ничего.
   */
  trainingTypeId: string | null;
  /**
   * Турнир, занявший это время. Обязателен при `purpose: 'TOURNAMENT'` и
   * возможен только в расписании конкретной даты: у турнира дата и время
   * проведения, и в постоянном шаблоне недели ему места нет.
   */
  tournamentId: string | null;
}

/** Окно шаблона недели: «каждый вторник с 15:00 до 19:00». */
export interface ClosureRule extends ClosureSlot {
  id: string;
  weekday: Weekday;
}

export type ClosureRuleDraft = Omit<ClosureRule, 'id'>;

/** Окно расписания конкретной даты. */
export interface DayClosure extends ClosureSlot {
  id: string;
}

export type DayClosureDraft = Omit<DayClosure, 'id'>;

/**
 * Замена расписания разом — и шаблона, и дня.
 *
 * Не поштучное добавление и удаление: администратор правит расписание в
 * сетке, где одно движение мыши меняет десяток окон сразу. Присылать разницу
 * значит собирать её на клиенте и надеяться, что она сошлась.
 */
export interface ReplaceTemplateRequest {
  rules: ClosureRuleDraft[];
}

export interface ReplaceDayRequest {
  closures: DayClosureDraft[];
}

/**
 * Расписание зала на конкретную дату.
 *
 * `customised: false` означает, что день не правили и действует шаблон недели;
 * `closures` тогда пуст. Пустое расписание правленого дня — осмысленное
 * состояние («в эту субботу тренировок нет»), и отличить его от «не правили»
 * можно только этим признаком.
 */
export interface DaySchedule {
  /** Календарная дата по времени клуба, «2026-03-12». */
  date: string;
  customised: boolean;
  closures: DayClosure[];
}

/** Тренер клуба — для выбора при назначении тренировки. */
export interface ClubCoach {
  id: string;
  fullName: string;
}

/**
 * Человек в клубе: сотрудник или клиент.
 *
 * Один список на все роли, а не три разных: администратору чаще нужно найти
 * человека, чем перебрать роль целиком, и поиск по общему списку короче.
 */
export interface ClubPerson {
  id: string;
  fullName: string;
  email: string;
  phone: string;
  /** Дата рождения, «2001-05-17». */
  birthDate: string;
  role: Role;
  /** Когда учётка заведена — по ней список и сортируется по умолчанию. */
  createdAt: string;
  /**
   * Отключённые не пропадают из списка, а помечаются: удаления в продукте нет,
   * а бухгалтерии и истории визитов человек по-прежнему нужен.
   */
  deactivated: boolean;
}

/** Страница списка людей: список неограничен, поэтому ходит порциями. */
export interface ClubPeoplePage {
  items: ClubPerson[];
  /** Сколько всего подходит под фильтр — для «показано 50 из 1240». */
  total: number;
}

/**
 * Смена роли человека.
 *
 * Повышение клиента до тренера и обратно — обычная жизнь клуба, и делать это
 * должен администратор, а не разработчик командой в консоли.
 */
export interface ChangeRoleRequest {
  role: Role;
}

export interface ClubPeopleQuery {
  /** Пусто — все роли. */
  role?: Role;
  /** Поиск по ФИО, почте и телефону. */
  search?: string;
  /**
   * Точечная выборка по идентификаторам.
   *
   * Нужна расписанию: в окнах лежат идентификаторы закреплённых клиентов, а
   * показать надо имена. Тянуть ради этого весь список клиентов клуба нельзя —
   * их тысячи.
   */
  ids?: string[];
  limit?: number;
  offset?: number;
}

/**
 * Тип тренировки: «Общая групповая», «Первая подача».
 *
 * Классификация нужна и клиенту (он выбирает, на что записаться), и кассе
 * (цена своя у каждого типа). Список ведёт администратор клуба.
 */
export interface TrainingType {
  id: string;
  name: string;
  /** Цена участия, копейки. */
  price: number;
  /**
   * Снятая с продажи не удаляется, а гасится: на неё ссылаются прошедшие
   * занятия и расписание, и удаление упёрлось бы во внешний ключ.
   */
  isActive: boolean;
  /** Сколько окон расписания на неё ссылается — показывается перед снятием. */
  usageCount: number;
}

export interface TrainingTypeRequest {
  name: string;
  price: number;
  isActive?: boolean;
}

/**
 * Тип турнира: «Клуб 100», «Первая подача».
 *
 * Часть названий несёт число-ограничение по рейтингу. Это справочная
 * информация для спортсмена — система её не проверяет и допуск не блокирует
 * (ТЗ → «Запись на турнир»).
 */
export interface TournamentType {
  id: string;
  name: string;
  /** Число-ограничение из названия, например «100». Ни на что не влияет. */
  ratingLabel: string | null;
  /** Цена участия, копейки. */
  price: number;
  isActive: boolean;
  /** Сколько турниров заведено по этому типу. */
  tournamentCount: number;
}

export interface TournamentTypeRequest {
  name: string;
  ratingLabel?: string | null;
  price: number;
  isActive?: boolean;
}

/** Турнир: конкретное проведение типа в конкретный момент. */
export interface Tournament {
  id: string;
  tournamentTypeId: string;
  /** Название типа — чтобы список читался без второго запроса. */
  typeName: string;
  /** Момент начала в ISO-8601 с зоной; хранится в UTC, как и брони. */
  startsAt: string;
  /** Сколько окон расписания уже отдано этому турниру. */
  placedCount: number;
}

export interface TournamentRequest {
  tournamentTypeId: string;
  startsAt: string;
}
