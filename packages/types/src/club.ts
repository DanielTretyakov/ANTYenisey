/**
 * Человек глазами клуба: карточка целиком.
 *
 * Один запрос на экран, как у смены: карточку открывают из состава клуба, из
 * «Требует отметки» и из отметок, и три ожидания вместо одного на таком пути
 * — умножение задержки на ровном месте.
 *
 * Всё, что здесь есть, — про ЭТОТ клуб. История в соседнем клубе того же
 * человека администратору не видна: её закрывает то же сужение по клубу, что
 * и остальные данные.
 */
export interface ClubPersonCard {
  person: ClubPerson;
  summary: ClubPersonSummary;
  /**
   * Записи: аренда, занятия и турниры. Свежие сверху — карточку открывают с
   * вопросом «что было», а не «что будет».
   */
  entries: ClubPersonEntry[];
  /** Визиты с порога: они не записи и в `entries` не попадают. */
  visits: DeskVisit[];
  /**
   * Профиль игрока — целиком, со сканом приказа и причиной отказа: разряд
   * проверяет администратор любого клуба человека, и смотрит он отсюда.
   */
  player: PlayerProfile;
  /** Семья: кто ведёт человека, кого ведёт он. */
  family: ClubPersonFamily;
  /**
   * Карточка тренера — только у тренера этого клуба, и её правит отсюда
   * администратор. У остальных пусто.
   */
  coach: CoachProfile | null;
}

/** Запись человека вместе с подписью того, кто поставил отметку. */
