/**
 * Контракт авторизации, общий для API и фронтенда.
 *
 * Здесь лежат только формы запросов и ответов, пересекающие границу HTTP.
 * Модели БД сюда не попадают: они приходят из `@yenisey/database` и содержат
 * поля, которых клиент видеть не должен (passwordHash, служебные отметки).
 */

/**
 * Роль пользователя внутри клуба. Значения совпадают с enum `Role` из
 * schema.prisma — при добавлении роли править оба места. Ролей у человека в
 * клубе бывает несколько сразу — см. `roles.ts`.
 */
export type Role = 'CLIENT' | 'ADMIN' | 'COACH' | 'MANAGER' | 'OWNER';

/**
 * Пол человека — ради рисованной заглушки вместо фотографии (решение
 * владельца от 25.09.2026). У учёток, заведённых раньше, может отсутствовать.
 */
export type Gender = 'MALE' | 'FEMALE';

export interface RegisterRequest {
  /**
   * Код клуба (Tenant.slug), если человек регистрируется со страницы клуба.
   *
   * Не обязателен: аккаунт заводится на ПЛАТФОРМЕ, а не в клубе, и вступать
   * куда-либо, чтобы им пользоваться, не нужно. Когда код передан, человек
   * заодно сразу становится клиентом этого клуба — иначе привязка появится
   * сама при первой записи.
   */
  tenantSlug?: string;
  email: string;
  password: string;
  /**
   * ФИО тремя отдельными полями, а не одной строкой.
   *
   * В базе оно всё равно хранится склеенным (ClientProfile.fullName), но
   * форма спрашивает по частям намеренно: в одно поле «ФИО» люди вписывают
   * что придётся — «Иван», «Иванов И.», «иванов иван» — и администратор
   * потом не может ни найти человека, ни обратиться к нему по имени.
   * Три обязательных поля этого не допускают.
   *
   * Отчество обязательно. Учтите, что у иностранцев и части народов России
   * его нет: если такие клиенты появятся, требование придётся ослабить.
   */
  lastName: string;
  firstName: string;
  middleName: string;
  /** Телефон в E.164: +79991234567. Основной канал связи клуба с клиентом. */
  phone: string;
  /**
   * Дата рождения, «2001-05-17». Обязательна: от неё зависят детские группы и
   * возрастные турниры, а спрашивать её потом, когда человек уже записался, —
   * значит не спросить никогда.
   */
  birthDate: string;
  /** Пол. Обязателен: по нему рисуется заглушка аватара без фотографии. */
  gender: Gender;
}

export interface LoginRequest {
  /**
   * Клуб не спрашивается. Человек входит на платформу, а клуб выбирает
   * дальше сам (ТЗ → «Один аккаунт на все клубы»): почта уникальна по всей
   * платформе, и уточнять, «в какой клуб он идёт», нечем и незачем.
   */
  email: string;
  password: string;
}

export interface RefreshRequest {
  /**
   * Не обязателен: браузер присылает refresh-токен в httpOnly-куке и тела
   * запроса не заполняет. Поле остаётся для клиентов без кук — мобильного
   * приложения на Capacitor.
   */
  refreshToken?: string;
}

/**
 * Членство аккаунта в клубе: кем человек является в этом конкретном клубе.
 *
 * Название и код клуба едут вместе с ролью не для красоты: интерфейсу нужно
 * показать список клубов человека, а второй запрос за названиями превратил бы
 * шапку страницы в два похода на сервер.
 */
export interface UserMembership {
  tenantId: string;
  /** Код клуба — он же участок адреса: /api/clubs/:slug/... */
  slug: string;
  name: string;
  /** Роли в этом клубе — несколько сразу; клиент — `['CLIENT']`. */
  roles: Role[];
}

/** Пользователь в том виде, в каком его отдаёт API — без секретов. */
/** Правка своих данных — ФИО частями и телефон. Почта и дата рождения — через клуб. */
export interface UpdateProfileRequest {
  lastName: string;
  firstName: string;
  middleName: string;
  phone: string;
  gender: Gender;
}

/** Смена своего пароля: текущий подтверждает, что меняет владелец. */
export interface ChangePasswordRequest {
  currentPassword: string;
  newPassword: string;
}

export interface PublicUser {
  id: string;
  email: string;
  phone: string;
  /** Дата рождения, «2001-05-17». */
  birthDate: string;
  /**
   * ФИО есть у любой роли: оно живёт в User, а не в профиле. У анонимизированной
   * учётки здесь плейсхолдер, а не null, — поле обязательное.
   */
  fullName: string;
  /** Пол; пусто у учёток, заведённых до 25.09.2026, пока его не указали. */
  gender: Gender | null;
  /**
   * Клубы этого аккаунта и роль в каждом. Роли «вообще на платформе» нет:
   * пустой список — нормальное состояние человека, который зарегистрировался,
   * но пока никуда не записывался.
   */
  memberships: UserMembership[];
  /**
   * Владелец платформы (`pnpm db:grant-platform`): пишет новости платформы.
   * Интерфейсу — чтобы показать ссылку на редактор; запрет стоит на сервере.
   */
  platformOwner: boolean;
}

export interface AuthTokens {
  /**
   * Живёт 15 минут и хранится клиентом только в памяти. В localStorage его
   * класть нельзя: оттуда его читает любой скрипт на странице.
   */
  accessToken: string;
  /**
   * Присутствует, только если клиент явно попросил его в теле — заголовком
   * `X-Auth-Transport: body`. Так делает мобильное приложение (Capacitor), где
   * кук нет. Браузеру токен приходит исключительно в httpOnly-куке, и здесь
   * поле остаётся пустым.
   */
  refreshToken?: string;
  /** Срок жизни access-токена в секундах — фронтенд обновляет его заранее. */
  expiresIn: number;
}

export interface AuthResponse extends AuthTokens {
  user: PublicUser;
}

/**
 * Полезная нагрузка access-токена.
 *
 * Здесь только «кто», без «где» и «кем». Клуб и роль в токен не кладутся
 * намеренно: аккаунт один на платформу, роль — свойство пары «человек +
 * клуб», и токен с зашитым клубом означал бы, что две вкладки на разные клубы
 * дерутся за одну сессию. Клуб приходит участком адреса
 * (/api/clubs/:slug/...), а роль в нём guard читает из TenantMembership.
 *
 * Плата за это — запрос к базе на каждый клубный маршрут. Она осознанная:
 * роль, снятая с человека в клубе, перестаёт действовать сразу, а не через
 * пятнадцать минут, когда истечёт выданный ему токен.
 */
export interface AccessTokenPayload {
  /** subject — User.id */
  sub: string;
}

/** Полезная нагрузка refresh-токена. */
export interface RefreshTokenPayload {
  sub: string;
  /** RefreshToken.id — по нему строка помечается отозванной при ротации. */
  jti: string;
}
