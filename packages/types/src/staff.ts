/**
 * Смены администраторов (решение владельца от 26.09.2026).
 *
 * Управляющий зала (или руководитель) назначает на каждый день одного или
 * нескольких администраторов, и только у них в этот день открывается
 * «Смена» — чтобы никто другой случайно ничего не внёс. Руководство работает
 * на смене всегда.
 */

/** Зал в «Расписании персонала»: кто им управляет и можно ли его планировать. */
export interface StaffHall {
  id: string;
  name: string;
  city: string | null;
  managerId: string | null;
  managerName: string | null;
  /** Может ли смотрящий назначать смены: руководитель — везде, управляющий — в своих залах. */
  canPlan: boolean;
}

/** Человек, которого можно поставить на смену или сделать управляющим. */
export interface StaffCandidate {
  id: string;
  fullName: string;
}

/** Смены зала на несколько недель вперёд. */
export interface StaffSchedule {
  hallId: string;
  /** Сегодня по часам зала, «2026-09-26»: раньше назначать нельзя. */
  today: string;
  /** Последний день, на который можно назначить. */
  until: string;
  /** Администраторы клуба — те, кого можно поставить на смену. */
  candidates: StaffCandidate[];
  days: { date: string; adminIds: string[] }[];
}

/** Кто работает в зале в этот день — список целиком. */
export interface StaffDayRequest {
  adminIds: string[];
}

/** Может ли смотрящий открыть «Смену» и кто сегодня на ней. */
export interface DeskAccess {
  allowed: boolean;
  /** Почему нет — «сегодня вы не работаете». */
  message: string | null;
  /** Администраторы зала на сегодня — «Фамилия И.». */
  onShift: string[];
}
